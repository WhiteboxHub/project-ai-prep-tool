// YouTube Background Uploader Service Worker

// We use IndexedDB to store the video blobs.
// This is exactly the same DB created by client/lib/indexedDB.ts
const DB_NAME = "AiPrepMediaDB";
const DB_VERSION = 1;
const STORE_NAME = "recordings";

async function openDB() {
  return new Promise((resolve, reject) => {
    const request = indexedDB.open(DB_NAME, DB_VERSION);
    request.onupgradeneeded = (event) => {
      const db = event.target.result;
      if (!db.objectStoreNames.contains(STORE_NAME)) {
        db.createObjectStore(STORE_NAME);
      }
    };
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error);
  });
}

async function getAllRecordings() {
  const db = await openDB();
  return new Promise((resolve, reject) => {
    const transaction = db.transaction([STORE_NAME], "readonly");
    const store = transaction.objectStore(STORE_NAME);
    const request = store.getAllKeys();
    
    request.onsuccess = () => {
      const keys = request.result;
      if (keys.length === 0) return resolve([]);
      
      const blobs = [];
      const dataReq = store.getAll();
      dataReq.onsuccess = () => {
        for (let i = 0; i < keys.length; i++) {
          blobs.push({ id: keys[i], blob: dataReq.result[i] });
        }
        resolve(blobs);
      };
      dataReq.onerror = () => reject(dataReq.error);
    };
    request.onerror = () => reject(request.error);
  });
}

async function deleteRecording(id) {
  const db = await openDB();
  return new Promise((resolve, reject) => {
    const transaction = db.transaction([STORE_NAME], "readwrite");
    const store = transaction.objectStore(STORE_NAME);
    const request = store.delete(id);
    request.onsuccess = () => resolve();
    request.onerror = () => reject(request.error);
  });
}

// Function to process the uploads
async function processUploads() {
  try {
    const recordings = await getAllRecordings();
    if (recordings.length === 0) {
      return;
    }

    console.log(`[YouTube SW] Found ${recordings.length} recordings to upload.`);

    for (const record of recordings) {
      // 1. Get Session URI from backend
      console.log(`[YouTube SW] Getting upload URI for ${record.id}`);
      const uriResponse = await fetch("http://localhost:8000/api/youtube/get-upload-uri", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          title: `AI Prep Intro: ${record.id}`,
          description: "Candidate Introduction Video generated by AI Prep Tool"
        })
      });

      if (!uriResponse.ok) {
        console.error("[YouTube SW] Failed to get upload URI", await uriResponse.text());
        continue;
      }

      const { uploadUrl } = await uriResponse.json();

      // 2. PUT the blob directly to YouTube
      console.log(`[YouTube SW] Uploading ${record.blob.size} bytes directly to YouTube...`);
      const uploadResponse = await fetch(uploadUrl, {
        method: "PUT",
        headers: {
          "Content-Type": "video/webm"
        },
        body: record.blob
      });

      if (!uploadResponse.ok) {
        console.error("[YouTube SW] Failed to upload to YouTube", await uploadResponse.text());
        continue;
      }

      const youtubeData = await uploadResponse.json();
      const videoId = youtubeData.id;
      console.log(`[YouTube SW] Upload success! Video ID: ${videoId}`);

      // 3. Update the Database and Playlist via Backend
      console.log(`[YouTube SW] Updating database and playlist...`);
      
      const updateResponse = await fetch("http://localhost:8000/api/youtube/update-video-url", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          local_id: record.id,
          video_id: videoId
        })
      });

      if (!updateResponse.ok) {
        console.error("[YouTube SW] Failed to update backend with YouTube ID", await updateResponse.text());
        continue;
      }

      // 4. Cleanup local IndexedDB
      console.log(`[YouTube SW] Cleaning up local IndexedDB storage for ${record.id}`);
      await deleteRecording(record.id);
    }
  } catch (err) {
    console.error("[YouTube SW] Error in upload process:", err);
  }
}

// Service worker event listeners
self.addEventListener("install", (event) => {
  self.skipWaiting();
  console.log("[YouTube SW] Installed.");
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
  console.log("[YouTube SW] Activated and claimed clients.");
  
  // Do an immediate check on startup
  processUploads();
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === 'NEW_RECORDING_READY') {
    console.log("[YouTube SW] Received NEW_RECORDING_READY event. Processing uploads...");
    processUploads();
  }
});

self.addEventListener("fetch", (event) => {
  // Let the browser handle network requests normally
});
